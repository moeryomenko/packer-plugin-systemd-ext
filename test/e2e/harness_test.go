// assertContains runs one subtest per required substring.
func assertContains(t *testing.T, file string, data []byte, wants []string) {
	t.Helper()
	for _, want := range wants {
		want := want
		t.Run("contains_"+subtestName(want), func(t *testing.T) {
			if !bytes.Contains(data, []byte(want)) {
				t.Errorf("%s must contain %q", file, want)
			}
		})
	}
}

