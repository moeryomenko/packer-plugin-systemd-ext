// --- skip-policy self-tests (documentation of the walk contract) ----------

// TestHarnessScanSkipPolicy locks in the documented skip policy so the walk
// cannot silently start scanning build artifacts or binary fixtures.
func TestHarnessScanSkipPolicy(t *testing.T) {
	for _, tt := range []struct {
		name string
		want bool
	}{
		{name: ".git", want: true},
		{name: ".out", want: true},
		{name: "output-persist-golden", want: true},
		{name: "packer_cache", want: true},
		{name: "bake", want: false},
		{name: "persist", want: false},
		{name: "fixtures", want: false},
		{name: "prereq", want: false},
	} {
		tt := tt
		t.Run("dir_"+subtestName(tt.name), func(t *testing.T) {
			if got := isSkippedDir(tt.name); got != tt.want {
				t.Errorf("isSkippedDir(%q) = %v, want %v", tt.name, got, tt.want)
			}
		})
	}
	for _, tt := range []struct {
		name string
		want bool
	}{
		{name: "manifest.json", want: true},
		{name: "template.pkr.hcl", want: false},
		{name: "run.sh", want: false},
	} {
		tt := tt
		t.Run("file_"+subtestName(tt.name), func(t *testing.T) {
			if got := isSkippedFile(tt.name); got != tt.want {
				t.Errorf("isSkippedFile(%q) = %v, want %v", tt.name, got, tt.want)
			}
		})
	}
	for _, tt := range []struct {
		name string
		want bool
	}{
		{name: "prereq.go", want: true},
		{name: "harness_test.go", want: true},
		{name: "run.sh", want: false},
		{name: "template.pkr.hcl", want: false},
	} {
		tt := tt
		t.Run("go_"+subtestName(tt.name), func(t *testing.T) {
			if got := isGoSource(tt.name); got != tt.want {
				t.Errorf("isGoSource(%q) = %v, want %v", tt.name, got, tt.want)
			}
		})
	}
	for _, tt := range []struct {
		name string
		data []byte
		want bool
	}{
		{name: "nul_byte", data: []byte{'a', 0, 'b'}, want: true},
		{name: "invalid_utf8", data: []byte{0xff, 0xfe, 0xfd}, want: true},
		{name: "plain_text", data: []byte("hello qemu\n"), want: false},
	} {
		tt := tt
		t.Run("binary_"+tt.name, func(t *testing.T) {
			if got := isBinary(tt.data); got != tt.want {
				t.Errorf("isBinary(%q) = %v, want %v", tt.name, got, tt.want)
			}
		})
	}
	for _, tt := range []struct {
		name string
		data []byte
		want int // expected number of QEMU-builder-remnant violations
	}{
		{name: "tool_token_run_sh", data: []byte("qemu-img convert -O raw"), want: 0},
		{name: "tool_token_template_comment", data: []byte("# boot disk converted with qemu-img"), want: 0},
		{name: "tool_package_name", data: []byte("package qemu-utils"), want: 0},
		{name: "prose_guest", data: []byte("Runs inside the QEMU guest"), want: 0},
		{name: "builder_source", data: []byte("source \"qemu\" \"bake\" {"), want: 1},
		{name: "builder_source_double_space", data: []byte("source  \"qemu\" {"), want: 1},
		{name: "qemu_system_binary", data: []byte("qemu-system-x86_64 -m 2G"), want: 1},
		{name: "hashicorp_plugin", data: []byte("source = \"github.com/hashicorp/qemu\""), want: 1},
		{name: "removed_script", data: []byte("run ./second-boot.sh"), want: 1},
		{name: "new_assert_script", data: []byte("runs assert-second-boot.sh"), want: 0},
	} {
		tt := tt
		t.Run("scan_"+subtestName(tt.name), func(t *testing.T) {
			hits := findQemuViolations(tt.data)
			if len(hits) != tt.want {
				t.Errorf("findQemuViolations(%q) = %d hit(s), want %d:\n%s",
					tt.data, len(hits), tt.want, strings.Join(hits, "\n"))
			}
		})
	}
}

// --- seed instance freshness + bake setcap parity --------------------------

// seedInstanceIDTimestampToken matches a `date +%s`-style per-run timestamp
// token (e.g. `$(date +%s)` or `$(date +%s%N)`), the evidence that a harness
// generates a unique NoCloud instance-id per run instead of reusing the
// constant id cloud-init cached on a previously booted raw disk.
var seedInstanceIDTimestampToken = regexp.MustCompile(`date[^\n]*\+%s`)

// seedInstanceIDInterpolation matches an `instance-id: ${VAR}` meta-data
// line, the alternative acceptable form where a variable carries the per-run
// id into the heredoc.
var seedInstanceIDInterpolation = regexp.MustCompile(`instance-id:\s*\$\{[A-Za-z_][A-Za-z0-9_]*\}`)

// TestHarnessSeedInstanceFreshness asserts both harness runners generate a
// per-run unique NoCloud instance-id. A constant instance-id (e.g.
// `instance-id: packer-bake-e2e`) makes cloud-init treat a reused writable
// raw disk as the SAME instance (new=False) and never re-apply the seed
// network-config, so the guest never gets the 10.0.2.2 / 192.168.249.2
// address the packer SSH communicator needs. Each file and each assertion is
// an independent t.Run subtest so partial failures are clear.
func TestHarnessSeedInstanceFreshness(t *testing.T) {
	root := repoRoot(t)
	for _, rel := range []string{"bake/run.sh", "persist/run.sh"} {
		rel := rel
		data := mustReadRepoFile(t, root, "test/e2e/"+rel)
		t.Run(subtestName(rel)+"_unique_instance_id", func(t *testing.T) {
			if !seedInstanceIDTimestampToken.Match(data) && !seedInstanceIDInterpolation.Match(data) {
				t.Errorf("%s must generate a per-run unique NoCloud instance-id: a `date +%%s`-style token or an instance-id variable interpolation into meta-data", rel)
			}
		})
		t.Run(subtestName(rel)+"_no_constant_instance_id", func(t *testing.T) {
			// Compare whole trimmed lines, not substrings: the fixed unique
			// form `instance-id: packer-bake-e2e-$(date +%s)` legitimately
			// contains the constant as a prefix and must not be flagged.
			constants := []string{
				"instance-id: packer-bake-e2e",
				"instance-id: packer-persist-e2e",
			}
			for _, line := range bytes.Split(data, []byte("\n")) {
				trimmed := string(bytes.TrimSpace(line))
				for _, c := range constants {
					if trimmed == c {
						t.Errorf("%s must not hardcode the constant instance-id %q (a per-run unique id is required)", rel, c)
					}
				}
			}
		})
	}
}

